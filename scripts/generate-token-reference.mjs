/**
 * Generates docs/BRIDGIO-TOKENS.md from src/styles/tokens.css.
 *
 * The doc is generated, never hand-edited: tokens.css stays the single source
 * of truth (C17). Run `npm run docs:tokens` after changing a token.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const source = readFileSync(join(process.cwd(), 'src', 'styles', 'tokens.css'), 'utf8')
const lines = source.split(/\r?\n/)
const darkStart = lines.findIndex((line) => line.includes(":root[data-theme='dark']"))

function sections(startLine, endLine) {
  const result = []
  let section = 'General'
  for (let index = startLine; index < endLine; index += 1) {
    const line = lines[index]
    const header = /\/\*\s*----\s*(.+?)\s*-+\s*\*\//.exec(line)
    if (header?.[1]) {
      section = header[1].replace(/\s+/g, ' ')
      continue
    }
    const declaration = /^\s*(--[a-z0-9-]+)\s*:\s*([^;]+);\s*(?:\/\*\s*(.*?)\s*\*\/)?/i.exec(line)
    if (!declaration?.[1]) continue
    result.push({
      section,
      name: declaration[1],
      value: declaration[2].trim(),
      comment: declaration[3]?.trim() ?? '',
      line: index + 1,
    })
  }
  return result
}

const light = sections(0, darkStart === -1 ? lines.length : darkStart)
const dark = sections(darkStart === -1 ? lines.length : darkStart, lines.length)

function table(rows) {
  const groups = new Map()
  for (const row of rows) {
    if (!groups.has(row.section)) groups.set(row.section, [])
    groups.get(row.section).push(row)
  }
  return [...groups.entries()]
    .map(([section, entries]) => {
      const body = entries
        .map(
          (entry) =>
            `| \`${entry.name}\` | \`${entry.value.replace(/\|/g, '\\|')}\` | ${entry.comment.replace(/\|/g, '\\|')} |`,
        )
        .join('\n')
      return `### ${section}\n\n| Token | Value | Note |\n| --- | --- | --- |\n${body}`
    })
    .join('\n\n')
}

const doc = `# BRIDGIO design tokens

> **Generated from \`src/styles/tokens.css\`.** Do not edit this file by hand;
> run \`npm run docs:tokens\`. Values marked LOCKED are brand decisions; values
> marked PROPOSED FOR UI are the MVP's working values, not brand locks.

## How to read this

- **LOCKED** — a brand decision. Use as-is.
- **PROPOSED FOR UI** — chosen for the MVP, labelled proposed in delivery notes.
- Light is the default theme. Dark is opt-in via \`data-theme="dark"\` on
  \`<html>\` and reuses the locked brand colours (brand maroon as the page,
  locked logo-outline as the surface, cream as ink).
- Dark overrides appear in their own table below; anything not listed there
  inherits the light value.

## Light theme (\`:root\`)

${table(light)}

## Dark theme (\`:root[data-theme='dark']\`)

${table(dark)}

## Motion ladder (C22)

The five steps are a phi ladder around the shipped 250 ms sidebar transition:
\`100 / 155 / 250 / 405 / 655 ms\`. Every transition and animation uses a
\`--motion-*\` token and \`--motion-ease\`; the global
\`prefers-reduced-motion: reduce\` rule in \`app.css\` collapses durations to
0.01 ms.

## Font roles (C13 / C41)

| Role | Stack token | Family chain |
| --- | --- | --- |
| Display | \`--font-stack-display\` | \`thmanyahserifdisplay\` → \`Bridgio Display\` (Sora) → sans-serif |
| Reading | \`--font-stack-reading\` | \`thmanyahseriftext\` → \`Bridgio Body\` (Nunito) → sans-serif |
| UI | \`--font-stack-ui\` | \`Bridgio Label\` (Alexandria 600 / 400 + Nunito 400) → sans-serif |

The Thmanyah woff2 files are not installed in Batch 0 (owner asset was not in
the session). The stacks request the family names first so the files light up
when added; nothing is substituted for a missing face.

## Type scale (desktop ≥ 1024 px)

The same tokens step up at the desktop breakpoint: hero 32, h1 34, h2 26,
h3 20, body 17, body-small 15, label 16. Caption stays 13.

## Guardrails

- \`src/styles/font-stacks.test.ts\` bans literal \`font-family\` declarations
  outside \`tokens.css\` / \`fonts.css\`.
- \`src/styles/tokens.contrast.test.ts\` checks the text pairs in both themes.
- \`npm run gate:contrast\` writes the full measurement, including C10 link
  visibility.
`

writeFileSync(join(process.cwd(), 'docs', 'BRIDGIO-TOKENS.md'), doc)
console.log(`Wrote docs/BRIDGIO-TOKENS.md (${light.length} light, ${dark.length} dark tokens).`)